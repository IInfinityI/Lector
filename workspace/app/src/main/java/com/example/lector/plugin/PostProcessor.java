package com.example.lector.plugin;

import com.example.lector.models.Lecture;

/**
 * Обработчик пост-обработки готовой лекции (аналог «модов-улучшателей» после записи).
 * Вызывается ядром один раз — когда запись остановлена и все блоки собраны.
 * Процессор может изменять блоки на месте (переупорядочивание, очистка текста,
 * добавление заголовков), но не должен выполнять долгий blocking I/O.
 */
public interface PostProcessor {

    /** Название процессора для отладки и UI. */
    String getName();

    /**
     * Обработка лекции. Изменения применяются напрямую к объекту Lecture.
     * Ядро вызывает процессоры в порядке регистрации и изолирует исключения.
     */
    void process(Lecture lecture);
}
